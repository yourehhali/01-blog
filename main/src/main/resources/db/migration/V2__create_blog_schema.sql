create table if not exists users (
    id bigint generated by default as identity primary key,
    username varchar(255) not null unique,
    email varchar(255) not null unique,
    password varchar(255) not null,
    role varchar(255) not null,
    active boolean not null default true,
    bio text,
    profile_picture varchar(255),
    created_at timestamp,
    updated_at timestamp
);

create table if not exists posts (
    id bigint generated by default as identity primary key,
    title varchar(255) not null,
    content text not null,
    author_id bigint not null,
    published boolean not null default false,
    hidden_by_admin boolean not null default false,
    created_at timestamp,
    updated_at timestamp,
    constraint fk_posts_author foreign key (author_id) references users(id)
);

create table if not exists post_media_urls (
    post_id bigint not null,
    media_url varchar(255) not null,
    constraint fk_post_media_post foreign key (post_id) references posts(id) on delete cascade
);

create table if not exists comments (
    id bigint generated by default as identity primary key,
    content text not null,
    author_id bigint not null,
    post_id bigint not null,
    created_at timestamp not null,
    constraint fk_comments_author foreign key (author_id) references users(id),
    constraint fk_comments_post foreign key (post_id) references posts(id)
);

create table if not exists likes (
    id bigint generated by default as identity primary key,
    post_id bigint not null,
    user_id bigint not null,
    created_at timestamp not null,
    constraint uk_likes_post_user unique (post_id, user_id),
    constraint fk_likes_post foreign key (post_id) references posts(id),
    constraint fk_likes_user foreign key (user_id) references users(id)
);

create table if not exists subscriptions (
    id bigint generated by default as identity primary key,
    subscriber_id bigint not null,
    target_id bigint not null,
    created_at timestamp not null,
    constraint uk_subscriptions_subscriber_target unique (subscriber_id, target_id),
    constraint fk_subscriptions_subscriber foreign key (subscriber_id) references users(id),
    constraint fk_subscriptions_target foreign key (target_id) references users(id)
);

create table if not exists notifications (
    id bigint generated by default as identity primary key,
    recipient_id bigint not null,
    message varchar(255) not null,
    is_read boolean not null default false,
    created_at timestamp not null,
    target_url varchar(255),
    constraint fk_notifications_recipient foreign key (recipient_id) references users(id)
);

create table if not exists reports (
    id bigint generated by default as identity primary key,
    reporter_id bigint not null,
    report_type varchar(255) not null,
    target_id bigint not null,
    reason text not null,
    created_at timestamp not null,
    constraint fk_reports_reporter foreign key (reporter_id) references users(id)
);

create table if not exists refresh_tokens (
    id bigint generated by default as identity primary key,
    token varchar(512) not null unique,
    user_id bigint not null,
    expiry timestamp not null,
    revoked boolean not null default false,
    created_at timestamp not null,
    constraint fk_refresh_tokens_user foreign key (user_id) references users(id)
);
